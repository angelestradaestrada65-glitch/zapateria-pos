-- =====================================================================
-- Zapatería POS - Script de base de datos (PostgreSQL)
-- Estructura de la base de datos del sistema POS (generada desde las entidades JPA)
--
-- Uso:
--   1) Crear la base:   CREATE DATABASE zapateria_db;
--   2) Conectarte a esa base y correr este script completo.
--
-- Nota: si la app tiene spring.jpa.hibernate.ddl-auto=update, Hibernate
-- también crea estas tablas solo. Este script sirve para recrear la
-- estructura a mano y para cargar datos iniciales.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. ESTRUCTURA
-- ---------------------------------------------------------------------

CREATE TABLE roles (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role_id       BIGINT       NOT NULL REFERENCES roles (id),
    active        BOOLEAN      NOT NULL
);

CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    brand       VARCHAR(255) NOT NULL,
    category_id BIGINT       NOT NULL REFERENCES categories (id),
    active      BOOLEAN      NOT NULL DEFAULT TRUE      -- FALSE = ya no se vende, pero conserva su historial
);

CREATE TABLE product_details (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT         NOT NULL REFERENCES products (id),
    size       VARCHAR(255)   NOT NULL,
    color      VARCHAR(255)   NOT NULL,
    price      NUMERIC(38, 2) NOT NULL,
    stock      INTEGER        NOT NULL
);

CREATE TABLE customers (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    phone  VARCHAR(255) NOT NULL,
    credit BOOLEAN      NOT NULL
);

CREATE TABLE sales (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_state  VARCHAR(255)   NOT NULL
                CHECK (sale_state IN ('PAID', 'ON_CREDIT', 'SETTLED', 'CANCELLED')),
    date        TIMESTAMP      NOT NULL,
    total       NUMERIC(38, 2) NOT NULL,
    amount_paid NUMERIC(38, 2) NOT NULL,
    user_id     BIGINT         NOT NULL REFERENCES users (id),
    customer_id BIGINT         REFERENCES customers (id)   -- opcional
);

CREATE TABLE sale_details (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id           BIGINT         NOT NULL REFERENCES sales (id),
    product_detail_id BIGINT         NOT NULL REFERENCES product_details (id),
    quantity          INTEGER        NOT NULL,
    unit_price        NUMERIC(38, 2) NOT NULL
);

CREATE TABLE payments (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT         NOT NULL REFERENCES sales (id),
    user_id BIGINT         NOT NULL REFERENCES users (id),   -- quien recibió el dinero
    amount  NUMERIC(38, 2) NOT NULL,
    date    TIMESTAMP      NOT NULL
);

